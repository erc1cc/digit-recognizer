"""Export the trained model to a self-contained web demo.

Batch-norm layers are folded into the preceding convolution/linear weights,
so the browser only has to implement conv -> relu -> maxpool -> linear.
Weights are written as a base64 float32 blob inside the HTML file.
"""

import base64
import json
from pathlib import Path

import numpy as np
import torch

from model import DigitCNN

ROOT = Path(__file__).resolve().parent.parent
CHECKPOINT = ROOT / "models" / "digit_cnn.pt"
OUT = ROOT / "web" / "weights.js"


def fold_conv_bn(conv_w, bn_w, bn_b, bn_mean, bn_var, eps=1e-5):
    """Merge BatchNorm into the convolution that feeds it."""
    scale = bn_w / torch.sqrt(bn_var + eps)
    w = conv_w * scale.reshape(-1, *([1] * (conv_w.dim() - 1)))
    b = bn_b - bn_mean * scale
    return w, b


def main():
    ckpt = torch.load(CHECKPOINT, map_location="cpu")
    model = DigitCNN()
    model.load_state_dict(ckpt["state_dict"])
    model.eval()

    f, c = model.features, model.classifier
    layers = []

    # (conv module index, batchnorm module index) pairs in `features`
    for conv_i, bn_i in [(0, 1), (3, 4), (8, 9), (11, 12)]:
        w, b = fold_conv_bn(
            f[conv_i].weight.data,
            f[bn_i].weight.data, f[bn_i].bias.data,
            f[bn_i].running_mean.data, f[bn_i].running_var.data,
        )
        layers.append({
            "type": "conv",
            "shape": list(w.shape),          # [out, in, kh, kw]
            "w": w.flatten().numpy(),
            "b": b.numpy(),
        })

    # classifier[1] Linear -> classifier[2] BatchNorm1d
    w, b = fold_conv_bn(
        c[1].weight.data,
        c[2].weight.data, c[2].bias.data,
        c[2].running_mean.data, c[2].running_var.data,
    )
    layers.append({"type": "fc", "shape": list(w.shape),
                   "w": w.flatten().numpy(), "b": b.numpy()})

    layers.append({"type": "fc", "shape": list(c[5].weight.data.shape),
                   "w": c[5].weight.data.flatten().numpy(),
                   "b": c[5].bias.data.numpy()})

    # Pack every tensor into one float32 buffer and record offsets.
    blob, meta, offset = [], [], 0
    for layer in layers:
        entry = {"type": layer["type"], "shape": layer["shape"]}
        for key in ("w", "b"):
            arr = np.asarray(layer[key], dtype=np.float32)
            blob.append(arr)
            entry[key] = [offset, arr.size]
            offset += arr.size
        meta.append(entry)

    packed = np.concatenate(blob).astype("<f4").tobytes()
    b64 = base64.b64encode(packed).decode("ascii")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Auto-generated by src/export_web.py -- do not edit by hand.\n"
        f"// test accuracy at export: {ckpt['accuracy'] * 100:.2f}%\n"
        f"const MODEL_META = {json.dumps(meta)};\n"
        f"const MODEL_ACCURACY = {ckpt['accuracy']:.4f};\n"
        f'const MODEL_B64 = "{b64}";\n'
    )
    print(f"wrote {OUT}  ({len(b64) / 1024:.0f} KB base64, "
          f"{offset:,} floats across {len(meta)} layers)")


if __name__ == "__main__":
    main()
